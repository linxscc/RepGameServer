#!/usr/bin/env python3
"""给 protoc 生成的 C# 解析代码换上具名的线上标签（wire tag）。

protoc 生成的 MergeFrom 里是 `switch(tag) { case 8: ... case 18: ... }`，数字是
线上标签 = 字段编号 << 3 | 线型（wire type），直接看看不出是哪个字段。本脚本：

1. 为每个 proto 模块生成 <Module>Tags.cs：每个消息一个 `<Message>Tag` 枚举，
   成员名就是字段名，值就是标签，注释写明字段编号、类型、线型和 .proto 里的说明；
2. 把生成代码里的 `case 8:` 改写为 `case (uint) ErrorTag.Code:`。

枚举值与原数字完全相同，编译结果不变。由 gen-proto.sh 在 protoc 之后自动调用，
不要手工修改生成的文件。

依赖：python3 + protobuf（pip install protobuf），用于读取 protoc 输出的描述符。
用法：gen-wire-tags.py <descriptor_set.pb> <C# 输出目录>
"""
import os
import re
import sys

from google.protobuf import descriptor_pb2 as d

F = d.FieldDescriptorProto

TYPE_NAME = {
    F.TYPE_DOUBLE: "double", F.TYPE_FLOAT: "float", F.TYPE_INT64: "int64", F.TYPE_UINT64: "uint64",
    F.TYPE_INT32: "int32", F.TYPE_FIXED64: "fixed64", F.TYPE_FIXED32: "fixed32", F.TYPE_BOOL: "bool",
    F.TYPE_STRING: "string", F.TYPE_BYTES: "bytes", F.TYPE_UINT32: "uint32", F.TYPE_SFIXED32: "sfixed32",
    F.TYPE_SFIXED64: "sfixed64", F.TYPE_SINT32: "sint32", F.TYPE_SINT64: "sint64",
}

# 线型：0 变长整数、1 定长 64 位、2 长度前缀、5 定长 32 位
WIRE_VARINT, WIRE_FIXED64, WIRE_LEN, WIRE_FIXED32 = 0, 1, 2, 5
WIRE_DESC = {WIRE_VARINT: "变长整数", WIRE_FIXED64: "定长 64 位", WIRE_LEN: "长度前缀", WIRE_FIXED32: "定长 32 位"}


def wire_type(f):
    if f.type in (F.TYPE_STRING, F.TYPE_BYTES, F.TYPE_MESSAGE):
        return WIRE_LEN
    if f.type in (F.TYPE_DOUBLE, F.TYPE_FIXED64, F.TYPE_SFIXED64):
        return WIRE_FIXED64
    if f.type in (F.TYPE_FLOAT, F.TYPE_FIXED32, F.TYPE_SFIXED32):
        return WIRE_FIXED32
    return WIRE_VARINT  # 整数、bool、enum


def pascal(name):
    """protoc C# 的属性命名：下划线分段、首字母大写（数字后的字母也大写）。"""
    out, upper = [], True
    for ch in name:
        if ch == "_":
            upper = True
            continue
        out.append(ch.upper() if upper else ch)
        upper = ch.isdigit()
    return "".join(out)


def type_label(f):
    t = f.type_name.rsplit(".", 1)[-1] if f.type in (F.TYPE_MESSAGE, F.TYPE_ENUM) else TYPE_NAME[f.type]
    if f.label == F.LABEL_REPEATED:
        return "repeated " + t
    return t


def comments(file_proto):
    """(消息下标, 字段下标) -> .proto 中该字段的注释（取前置或行尾注释，压成一行）"""
    out = {}
    for loc in file_proto.source_code_info.location:
        p = list(loc.path)
        if len(p) == 4 and p[0] == 4 and p[2] == 2:  # message_type[i].field[j]
            text = (loc.trailing_comments or loc.leading_comments).strip()
            if text:
                out[(p[1], p[3])] = " ".join(text.split())
    return out


def tags_for(msg, notes, mi):
    """消息的 [(标签, 成员名, 注释)]，按标签排序。"""
    rows = []
    for fi, f in enumerate(msg.field):
        name = pascal(f.name)
        wt = wire_type(f)
        note = notes.get((mi, fi), "")
        base = "字段 %d %s（%s）" % (f.number, f.name, type_label(f))
        packable = f.label == F.LABEL_REPEATED and wt != WIRE_LEN
        if packable:
            # repeated 数值字段：proto3 默认打包发送（长度前缀），解析时也接受逐个发送
            rows.append((f.number << 3 | WIRE_LEN, name, base + "，打包形式" + ("：" + note if note else "")))
            rows.append((f.number << 3 | wt, name + "Unpacked", base + "，逐个形式（%s）" % WIRE_DESC[wt]))
        else:
            rows.append((f.number << 3 | wt, name, base + "，" + WIRE_DESC[wt] + ("：" + note if note else "")))
    return sorted(rows)


def module_name(proto_path):
    return pascal(os.path.splitext(os.path.basename(proto_path))[0])


def main(desc_path, cs_dir):
    fs = d.FileDescriptorSet()
    fs.ParseFromString(open(desc_path, "rb").read())

    for fp in fs.file:
        if not fp.name.startswith("repgame/"):
            continue
        module = module_name(fp.name)
        notes = comments(fp)
        table = {}  # message -> {tag: member}
        lines = [
            "// <auto-generated>",
            "//     由 scripts/gen-wire-tags.py 根据 %s 生成，不要手工修改。" % fp.name,
            "// </auto-generated>",
            "//",
            "// 线上标签（wire tag）= 字段编号 << 3 | 线型。%s.cs 的解析代码用这些枚举区分字段，" % module,
            "// 值与 protoc 生成的数字完全相同。",
            "",
            "namespace RepGame.Protocol",
            "{",
        ]
        for mi, msg in enumerate(fp.message_type):
            rows = tags_for(msg, notes, mi)
            table[msg.name] = {tag: member for tag, member, _ in rows}
            lines.append("    /// <summary>%s 的字段标签</summary>" % msg.name)
            lines.append("    public enum %sTag : uint" % msg.name)
            lines.append("    {")
            for tag, member, note in rows:
                lines.append("        /// <summary>%s</summary>" % note.replace("<", "&lt;").replace(">", "&gt;"))
                lines.append("        %s = %d," % (member, tag))
            lines.append("    }")
            lines.append("")
        lines[-1] = "}"
        out_tags = os.path.join(cs_dir, module + "Tags.cs")
        open(out_tags, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")

        rewrite(os.path.join(cs_dir, module + ".cs"), table)
        print("%s: %d messages" % (module, len(table)))


CLASS_RE = re.compile(r"^\s*public sealed partial class (\w+) : pb::IMessage<")
# 打包的 repeated 字段会生成两个相邻 case（`case 18:` 贯穿到 `case 16: {`），后缀可有可无
CASE_RE = re.compile(r"^(\s*)case (\d+):( \{)?$")


def rewrite(path, table):
    """把消息类里 switch(tag) 的数字 case 换成对应的枚举成员。未知标签直接报错。"""
    src = open(path, encoding="utf-8").read().split("\n")
    current = None
    for i, line in enumerate(src):
        m = CLASS_RE.match(line)
        if m:
            current = m.group(1)
            continue
        m = CASE_RE.match(line)
        if m and current:
            tag = int(m.group(2))
            member = table.get(current, {}).get(tag)
            if member is None:
                raise SystemExit("%s: %s has no field for tag %d (line %d)" % (path, current, tag, i + 1))
            src[i] = "%scase (uint) %sTag.%s:%s" % (m.group(1), current, member, m.group(3) or "")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(src))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
