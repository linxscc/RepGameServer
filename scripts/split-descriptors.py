#!/usr/bin/env python3
"""把 protoc 生成代码里的描述符数据移到单独的文件，代码文件里只留代码。

描述符（descriptor）是 .proto 编译后的 schema，protobuf 运行时靠它解析消息。
它必须和解析代码出自同一次 protoc、一起编译进程序（不能做成运行时读取的配置文件：
版本可能对不上；C# 在后台网络线程首次用到消息时就要它，Unity 在那时不能同步读文件；
Go 在 init() 阶段就注册它）。所以这里只是换个文件存放，内容和编译结果不变：

  C#  <Module>.cs 静态构造里的 Base64 串 -> <Module>Descriptor.cs 里的常量 DescriptorBase64
  Go  <module>.pb.go 里的 file_..._rawDesc  -> <module>_desc.pb.go

由 gen-proto.sh 在 protoc 之后自动调用，不要手工修改生成的文件。
用法：split-descriptors.py <Go 输出目录> <C# 输出目录> <模块名...>
"""
import os
import re
import sys


def pascal(name):
    return "".join(p[:1].upper() + p[1:] for p in name.split("_"))


CS_CALL = re.compile(
    r"global::System\.Convert\.FromBase64String\(\s*string\.Concat\(\s*((?:\"[^\"]*\",?\s*)+)\)\);")


def split_cs(cs_dir, module):
    path = os.path.join(cs_dir, pascal(module) + ".cs")
    src = open(path, encoding="utf-8").read()
    m = CS_CALL.search(src)
    if not m:
        raise SystemExit("%s: descriptor data not found" % path)
    chunks = re.findall(r"\"[^\"]*\"", m.group(1))
    cls = re.search(r"public static partial class (\w+Reflection)", src).group(1)

    src = src[:m.start()] + "global::System.Convert.FromBase64String(DescriptorBase64);" + src[m.end():]
    open(path, "w", encoding="utf-8", newline="\n").write(src)

    body = "\n          + ".join(chunks)
    out = """// <auto-generated>
//     由 scripts/split-descriptors.py 从 protoc 的输出中拆出，不要手工修改。
//     source: repgame/v1/%(module)s.proto
// </auto-generated>
//
// repgame/v1/%(module)s.proto 编译后的描述符（schema），Base64 编码。
// %(pascal)s.cs 在静态构造里用它建立消息的反射信息；它必须与 %(pascal)s.cs 出自同一次生成。

namespace RepGame.Protocol {

  public static partial class %(cls)s {

    /// <summary>repgame/v1/%(module)s.proto 的描述符数据（Base64）</summary>
    private const string DescriptorBase64 =
          %(body)s;

  }

}
""" % {"module": module, "pascal": pascal(module), "cls": cls, "body": body}
    open(os.path.join(cs_dir, pascal(module) + "Descriptor.cs"), "w", encoding="utf-8", newline="\n").write(out)


def split_go(go_dir, module):
    path = os.path.join(go_dir, module + ".pb.go")
    lines = open(path, encoding="utf-8").read().split("\n")
    name = "file_repgame_v1_%s_proto_rawDesc" % module
    start = next((i for i, l in enumerate(lines) if l.startswith("var %s = " % name)), None)
    if start is None:
        raise SystemExit("%s: %s not found" % (path, name))
    end = next(i for i in range(start, len(lines)) if lines[i] == "})")
    block = lines[start:end + 1]
    # 去掉块后紧跟的空行，避免留下两个空行
    rest = lines[:start] + lines[end + 1:]
    if start < len(rest) and rest[start] == "" and rest[start - 1] == "":
        del rest[start]
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(rest))

    out = ["// Code generated by scripts/split-descriptors.py from protoc-gen-go output. DO NOT EDIT.",
           "// source: repgame/v1/%s.proto" % module, "",
           "package pb", "",
            "// %s 是 repgame/v1/%s.proto 编译后的描述符（schema），由 %s.pb.go 在 init 时注册。" % (name, module, module),
            "// 必须与 %s.pb.go 出自同一次生成。" % module] + block + [""]
    open(os.path.join(go_dir, module + "_desc.pb.go"), "w", encoding="utf-8", newline="\n").write("\n".join(out))


def main(go_dir, cs_dir, modules):
    for module in modules:
        split_cs(cs_dir, module)
        split_go(go_dir, module)
        print("%s: descriptor moved out" % module)


if __name__ == "__main__":
    if len(sys.argv) < 4:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2], sys.argv[3:])
